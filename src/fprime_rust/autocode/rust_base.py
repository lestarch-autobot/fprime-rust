"""fprime_rust.autocode.rust_base:

Generates ``<comp>_base.rs``: the ``Component`` trait, ``Context<'call>`` / ``InitContext`` helpers, the FPP
enums the component uses and the ``#[no_mangle] extern "C"`` entry points the C++ shim calls.
"""
from __future__ import annotations

from typing import List, Optional

from . import names
from .view import Command, ComponentView, Event, InternalPort, Param, Port, TypeInfo

HEADER = "// Generated by fprime-rust-ac; do not edit. Base module of {qualified} (model: {model})\n"



def rust_user_type(type_: TypeInfo) -> str:
    """Type as the user sees it in trait methods and helpers"""
    return "&str" if type_.kind == "string" else type_.rust


def rust_return_type(type_: Optional[TypeInfo]) -> str:
    if type_ is None:
        return ""
    return " -> String" if type_.kind == "string" else f" -> {type_.rust}"


def ffi_params_rust(params: List[Param]) -> List[str]:
    out = []
    for param in params:
        if param.type.kind == "string":
            out += [f"{param.name}_ptr: *const u8", f"{param.name}_len: FwSizeType"]
        else:
            out.append(f"{param.name}: {param.type.ffi}")
    return out


def user_params(params: List[Param]) -> List[str]:
    return [f"{param.name}: {rust_user_type(param.type)}" for param in params]


def decode_statements(params: List[Param]) -> List[str]:
    """Statements turning FFI carriers into user values (inside an unsafe entry point)"""
    out = []
    for param in params:
        type_ = param.type
        if type_.kind == "string":
            out.append(f"let {param.name} = unsafe {{ fprime_rust::str_arg({param.name}_ptr, {param.name}_len as usize) }};")
        elif type_.kind == "bool":
            out.append(f"let {param.name} = {param.name} != 0;")
        elif type_.kind == "enum":
            out.append(f"let {param.name} = fprime_rust::enum_from_repr({param.name}, {type_.rust}::from_repr, \"{type_.enum.qualified_name}\");")
    return out


def user_args(params: List[Param]) -> List[str]:
    return [f"&{param.name}" if param.type.kind == "string" else param.name for param in params]


def encode_args(params: List[Param]) -> List[str]:
    """Arguments passing user values to a shim helper"""
    out = []
    for param in params:
        type_ = param.type
        if type_.kind == "string":
            out += [f"{param.name}.as_ptr()", f"{param.name}.len() as FwSizeType"]
        elif type_.kind == "bool":
            out.append(f"u8::from({param.name})")
        elif type_.kind == "enum":
            out.append(f"{param.name}.repr()")
        else:
            out.append(param.name)
    return out


def _enum_block(view: ComponentView) -> List[str]:
    lines: List[str] = []
    for info in view.enums:
        lines += ["", f"/// FPP enum `{info.qualified_name}`", f"#[repr({info.repr})]",
                  "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]", f"pub enum {info.rust_name} {{"]
        lines += [f"    {name} = {value}," for name, value in info.constants]
        lines += ["}", "", f"impl {info.rust_name} {{",
                  "    /// Decode the FFI carrier", f"    pub const fn from_repr(value: {info.repr}) -> Option<Self> {{",
                  "        match value {"]
        lines += [f"            {value} => Some({info.rust_name}::{name})," for name, value in info.constants]
        lines += ["            _ => None,", "        }", "    }", "",
                  "    /// The FFI carrier", f"    pub const fn repr(self) -> {info.repr} {{", f"        self as {info.repr}", "    }", "}"]
    return lines


def _trait_block(view: ComponentView) -> List[str]:
    lines = ["", f"/// Handlers of `{view.qualified_name}`; implemented by `{view.name}` in `{view.name}.rs`",
             "pub trait Component: Sized {",
             "    /// Construct the implementation (called by the shim constructor, before `init`)",
             "    fn new() -> Self;", "",
             "    /// Initialize: no port, event, telemetry or parameter access yet",
             "    fn init(&mut self, ctx: &InitContext<'_>) {", "        let _ = ctx;", "    }"]
    for port in view.input_ports:
        params = ", ".join(["&mut self", "ctx: &mut Context<'_>", "port_num: FwIndexType"] + user_params(port.params))
        lines += ["", f"    /// `{port.kind}` input port `{port.name}` ({port.port_qualified_name})",
                  f"    fn {names.rust_handler(port)}({params}){rust_return_type(port.returns)};"]
        if port.hook:
            lines += ["", f"    /// Overflow hook of `{port.name}`: the queue was full",
                      f"    fn {names.rust_overflow_hook(port)}({params});"]
    for port in view.internal_ports:
        params = ", ".join(["&mut self", "ctx: &mut Context<'_>"] + user_params(port.params))
        lines += ["", f"    /// Internal port `{port.name}`", f"    fn {names.rust_internal_handler(port)}({params});"]
        if port.hook:
            lines += ["", f"    /// Overflow hook of internal port `{port.name}` (called by the invoking handler, no re-lock)",
                      f"    fn {names.rust_overflow_hook(port)}({params});"]
    for command in view.commands:
        params = ", ".join(["&mut self", "ctx: &mut Context<'_>"] + user_params(command.params))
        lines += ["", f"    /// `{command.kind}` command `{command.name}` (opcode {command.opcode})",
                  f"    fn {names.rust_cmd_handler(command)}({params}) -> CmdResponse;"]
        if command.hook:
            lines += ["", f"    /// Overflow hook of command `{command.name}`: the returned response is sent for the command",
                      f"    fn {names.rust_overflow_hook(command)}(&mut self, ctx: &mut Context<'_>, opcode: FwOpcodeType, cmd_seq: u32) -> CmdResponse;"]
    lines += ["", "    /// A parameter was set (`PRM_SET`) or loaded at start-up",
              "    fn parameter_updated(&mut self, ctx: &mut Context<'_>, id: FwPrmIdType) {",
              "        let _ = (ctx, id);", "    }", "}"]
    return lines


def _context_block(view: ComponentView) -> List[str]:
    lines = ["", "/// Context of `init`: no port, event, telemetry or parameter access",
             "pub struct InitContext<'call> {", "    raw: &'call mut RawContext,", "    _marker: NotThreadSafe,", "}", "",
             "impl<'call> InitContext<'call> {",
             "    /// Opaque identity of the component instance (for logging only)",
             "    pub fn component_id(&self) -> usize {", "        self.raw.component as usize", "    }", "}", "",
             f"/// Per-call context of `{view.qualified_name}`: output ports, events, telemetry and parameters.",
             "/// Borrows the shim's stack frame for one call: neither `Send` nor `Sync`.",
             "pub struct Context<'call> {", "    raw: &'call mut RawContext,", "    _marker: NotThreadSafe,", "}", "",
             "impl<'call> Context<'call> {",
             "    /// Status of the queue drain that preceded this call (queued components; `Empty` otherwise)",
             "    pub fn last_dispatch(&self) -> MsgDispatchStatus {",
             "        MsgDispatchStatus::from_code(self.raw.last_dispatch)", "    }"]
    if view.is_queued_kind:
        lines += ["", "    /// Number of messages dropped from the queue (`getNumMsgsDropped`)",
                  "    pub fn num_msgs_dropped(&self) -> FwSizeType {",
                  f"        unsafe {{ ffi::{names.num_msgs_dropped(view)}(self.raw.component) }}", "    }"]
    for port in view.output_ports:
        params = ", ".join(["&mut self", "port_num: FwIndexType"] + user_params(port.params))
        args = ["self.raw.component", "port_num"] + encode_args(port.params)
        lines += ["", f"    /// Output port `{port.name}` ({port.port_qualified_name})",
                  f"    pub fn {names.rust_out(port)}({params}){rust_return_type(port.returns)} {{"]
        lines += _call_with_result(f"ffi::{names.out(view, port)}", args, port.returns)
        lines.append("    }")
    for port in view.internal_ports:
        params = ", ".join(["&mut self"] + user_params(port.params))
        args = ["self.raw.component"] + encode_args(port.params)
        lines += ["", f"    /// Invoke internal port `{port.name}` (queued to this instance)",
                  f"    pub fn {names.rust_internal_invoke(port)}({params}) {{",
                  f"        unsafe {{ ffi::{names.internal_invoke(view, port)}({', '.join(args)}) }}", "    }"]
    for event in view.events:
        params = ", ".join(["&mut self"] + user_params(event.params))
        args = ["self.raw.component"] + encode_args(event.params)
        lines += ["", f"    /// Log event `{event.name}` (severity {event.severity})",
                  f"    pub fn {names.rust_log(event)}({params}) {{",
                  f"        unsafe {{ ffi::{names.log(view, event)}({', '.join(args)}) }}", "    }"]
    for channel in view.channels:
        value = Param("value", channel.type)
        args = ["self.raw.component"] + encode_args([value])
        lines += ["", f"    /// Write telemetry channel `{channel.name}`",
                  f"    pub fn {names.rust_tlm_write(channel)}(&mut self, value: {rust_user_type(channel.type)}) {{",
                  f"        unsafe {{ ffi::{names.tlm_write(view, channel)}({', '.join(args)}) }}", "    }"]
    for parameter in view.parameters:
        type_ = parameter.type
        ret = "String" if type_.kind == "string" else type_.rust
        lines += ["", f"    /// Read parameter `{parameter.name}` and its validity",
                  f"    pub fn {names.rust_param_get(parameter)}(&mut self) -> ({ret}, ParamValid) {{"]
        if type_.kind == "string":
            lines += [f"        let mut buffer = [0u8; {type_.rust_string_capacity(f'parameter {parameter.name}')}];", "        let mut length: FwSizeType = 0;",
                      f"        let valid = unsafe {{ ffi::{names.param_get(view, parameter)}(self.raw.component, buffer.as_mut_ptr(), buffer.len() as FwSizeType, &mut length) }};",
                      "        let value = String::from_utf8_lossy(&buffer[..length as usize]).into_owned();"]
        else:
            lines += [f"        let mut carrier: {type_.ffi} = 0;",
                      f"        let valid = unsafe {{ ffi::{names.param_get(view, parameter)}(self.raw.component, &mut carrier) }};"]
            if type_.kind == "bool":
                lines.append("        let value = carrier != 0;")
            elif type_.kind == "enum":
                lines.append(f"        let value = fprime_rust::enum_from_repr(carrier, {type_.rust}::from_repr, \"{type_.enum.qualified_name}\");")
            else:
                lines.append("        let value = carrier;")
        lines += ["        (value, ParamValid::from_code(valid))", "    }"]
    lines.append("}")
    return lines


def _call_with_result(function: str, args: List[str], returns: Optional[TypeInfo]) -> List[str]:
    if returns is None:
        return [f"        unsafe {{ {function}({', '.join(args)}) }}"]
    if returns.kind == "string":
        return [f"        let mut buffer = [0u8; {returns.rust_string_capacity('port return')}];", "        let mut length: FwSizeType = 0;",
                f"        unsafe {{ {function}({', '.join(args + ['buffer.as_mut_ptr()', 'buffer.len() as FwSizeType', '&mut length'])}) }};",
                "        String::from_utf8_lossy(&buffer[..length as usize]).into_owned()"]
    lines = [f"        let mut result: {returns.ffi} = 0;",
             f"        unsafe {{ {function}({', '.join(args + ['&mut result'])}) }};"]
    if returns.kind == "bool":
        lines.append("        result != 0")
    elif returns.kind == "enum":
        lines.append(f"        fprime_rust::enum_from_repr(result, {returns.rust}::from_repr, \"{returns.enum.qualified_name}\")")
    else:
        lines.append("        result")
    return lines


def _ffi_block(view: ComponentView) -> List[str]:
    lines = ["", "/// Helpers exported by the C++ shim", "mod ffi {", "    use super::*;", "", "    extern \"C\" {"]
    for port in view.output_ports:
        params = ["component: *mut c_void", "port_num: FwIndexType"] + ffi_params_rust(port.params) + _helper_result_params(port.returns)
        lines.append(f"        pub fn {names.out(view, port)}({', '.join(params)});")
    for port in view.internal_ports:
        lines.append(f"        pub fn {names.internal_invoke(view, port)}({', '.join(['component: *mut c_void'] + ffi_params_rust(port.params))});")
    for event in view.events:
        lines.append(f"        pub fn {names.log(view, event)}({', '.join(['component: *mut c_void'] + ffi_params_rust(event.params))});")
    for channel in view.channels:
        lines.append(f"        pub fn {names.tlm_write(view, channel)}({', '.join(['component: *mut c_void'] + ffi_params_rust([Param('value', channel.type)]))});")
    for parameter in view.parameters:
        if parameter.type.kind == "string":
            params = ["component: *mut c_void", "buffer: *mut u8", "capacity: FwSizeType", "length: *mut FwSizeType"]
        else:
            params = ["component: *mut c_void", f"value: *mut {parameter.type.ffi}"]
        lines.append(f"        pub fn {names.param_get(view, parameter)}({', '.join(params)}) -> u8;")
    if view.is_queued_kind:
        lines.append(f"        pub fn {names.num_msgs_dropped(view)}(component: *mut c_void) -> u64;")
    lines += ["    }", "}"]
    return lines


def _helper_result_params(returns: Optional[TypeInfo]) -> List[str]:
    if returns is None:
        return []
    if returns.kind == "string":
        return ["buffer: *mut u8", "capacity: FwSizeType", "length: *mut FwSizeType"]
    return [f"result: *mut {returns.ffi}"]


def _entry(name: str, params: List[str], body: List[str], returns: str = "") -> List[str]:
    lines = ["", "#[no_mangle]", f"pub unsafe extern \"C\" fn {name}({', '.join(params)}){returns} {{"]
    lines += [f"    {line}" for line in body]
    lines.append("}")
    return lines


ENTRY_PRELUDE = [
    "// SAFETY: the shim passes its own live Box<Implementation> and a context borrowed for this call",
    "let this = unsafe { &mut *(fpr_impl as *mut Implementation) };",
    "let mut ctx = Context { raw: unsafe { &mut *fpr_ctx }, _marker: NotThreadSafe::new() };",
]


def _entries_block(view: ComponentView) -> List[str]:
    lines: List[str] = []
    lines += _entry(names.lifecycle(view, "new"), [], [
        "fprime_rust::install_panic_hook();",
        "Box::into_raw(Box::new(<Implementation as Component>::new())) as *mut c_void",
    ], " -> *mut c_void")
    lines += _entry(names.lifecycle(view, "drop"), ["fpr_impl: *mut c_void"], [
        "if !fpr_impl.is_null() {",
        "    // SAFETY: the pointer came from `_new` and the shim drops it exactly once",
        "    drop(unsafe { Box::from_raw(fpr_impl as *mut Implementation) });",
        "}",
    ])
    lines += _entry(names.lifecycle(view, "init"), ["fpr_impl: *mut c_void", "fpr_ctx: *mut RawContext"], [
        "let this = unsafe { &mut *(fpr_impl as *mut Implementation) };",
        "let ctx = InitContext { raw: unsafe { &mut *fpr_ctx }, _marker: NotThreadSafe::new() };",
        "this.init(&ctx);",
    ])
    lines += _entry(names.parameter_updated(view), ["fpr_impl: *mut c_void", "fpr_ctx: *mut RawContext", "fpr_id: FwPrmIdType"],
                    ENTRY_PRELUDE + ["this.parameter_updated(&mut ctx, fpr_id);"])
    base = ["fpr_impl: *mut c_void", "fpr_ctx: *mut RawContext"]
    for port in view.input_ports:
        params = base + ["fpr_port_num: FwIndexType"] + ffi_params_rust(port.params) + _result_params(port.returns)
        call = f"this.{names.rust_handler(port)}({', '.join(['&mut ctx', 'fpr_port_num'] + user_args(port.params))})"
        lines += _entry(names.handler(view, port), params, ENTRY_PRELUDE + decode_statements(port.params) + _store_result(call, port.returns))
        if port.hook:
            params = base + ["fpr_port_num: FwIndexType"] + ffi_params_rust(port.params)
            call = f"this.{names.rust_overflow_hook(port)}({', '.join(['&mut ctx', 'fpr_port_num'] + user_args(port.params))});"
            lines += _entry(names.overflow_hook(view, port), params, ENTRY_PRELUDE + decode_statements(port.params) + [call])
    for port in view.internal_ports:
        params = base + ffi_params_rust(port.params)
        call = f"this.{names.rust_internal_handler(port)}({', '.join(['&mut ctx'] + user_args(port.params))});"
        lines += _entry(names.internal_handler(view, port), params, ENTRY_PRELUDE + decode_statements(port.params) + [call])
        if port.hook:
            call = f"this.{names.rust_overflow_hook(port)}({', '.join(['&mut ctx'] + user_args(port.params))});"
            lines += _entry(names.overflow_hook(view, port), params, ENTRY_PRELUDE + decode_statements(port.params) + [call])
    for command in view.commands:
        params = base + ffi_params_rust(command.params)
        call = f"this.{names.rust_cmd_handler(command)}({', '.join(['&mut ctx'] + user_args(command.params))}).code()"
        lines += _entry(names.cmd_handler(view, command), params, ENTRY_PRELUDE + decode_statements(command.params) + [call], " -> u32")
        if command.hook:
            lines += _entry(names.overflow_hook(view, command), base + ["fpr_opcode: FwOpcodeType", "fpr_cmd_seq: u32"],
                            ENTRY_PRELUDE + [f"this.{names.rust_overflow_hook(command)}(&mut ctx, fpr_opcode, fpr_cmd_seq).code()"], " -> u32")
    return lines


def _result_params(returns: Optional[TypeInfo]) -> List[str]:
    if returns is None:
        return []
    return ["fpr_result: *mut c_void"] if returns.kind == "string" else [f"fpr_result: *mut {returns.ffi}"]


def _store_result(call: str, returns: Optional[TypeInfo]) -> List[str]:
    if returns is None:
        return [f"{call};"]
    if returns.kind == "string":
        return [f"let value = {call};", "unsafe { fprime_rust::assign_string(fpr_result, &value) };"]
    if returns.kind == "bool":
        return [f"let value = u8::from({call});", "unsafe { *fpr_result = value };"]
    if returns.kind == "enum":
        return [f"let value = {call}.repr();", "unsafe { *fpr_result = value };"]
    return [f"let value = {call};", "unsafe { *fpr_result = value };"]


def generate(view: ComponentView, model_name: str) -> str:
    lines = [HEADER.format(qualified=view.qualified_name, model=model_name).rstrip("\n"),
             "#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals, dead_code, unused_imports, clippy::all)]", "",
             "use std::ffi::c_void;", "",
             "pub use fprime_rust::{CmdResponse, MsgDispatchStatus, NotThreadSafe, ParamValid, RawContext};", "",
             f"/// The user's implementation: `pub struct {view.name}` in `{view.name}.rs`",
             f"pub type Implementation = crate::{view.user_module}::{view.name};", "",
             "// F Prime platform integer types, as resolved in this model"]
    lines += [f"pub type {name} = {rust};" for name, rust in view.platform_types.items()]
    lines += _enum_block(view)
    lines += _trait_block(view)
    lines += _context_block(view)
    lines += _ffi_block(view)
    lines += _entries_block(view)
    lines.append("")
    return "\n".join(lines)
