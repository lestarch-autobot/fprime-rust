"""fprime_rust.autocode.crate:

Emits the deployment-level Cargo workspace (REQ-FprimeRust-018): one rlib member per Rust component wrapping
its generated base module and the user's ``<Comp>.rs``, and one staticlib root whose ``lib.rs`` re-exports
every member and the runtime, so each executable links exactly one Rust archive.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List

CLIPPY_DENY = ("unwrap_used", "expect_used", "indexing_slicing", "arithmetic_side_effects")
PROFILE_SETTINGS = ["panic = \"abort\"", "lto = true", "overflow-checks = false"]


@dataclass(frozen=True)
class CrateMember:
    """One Rust component in the workspace"""

    qualified_name: str   # Ns.Comp
    base_file: Path       # generated <comp>_base.rs
    user_file: Path       # user <Comp>.rs

    @property
    def name(self) -> str:
        return self.qualified_name.replace(".", "_").lower()

    @property
    def component_name(self) -> str:
        return self.qualified_name.rsplit(".", 1)[-1]

    @property
    def base_module(self) -> str:
        return f"{self.component_name.lower()}_base"

    @property
    def user_module(self) -> str:
        return self.component_name.lower()


def root_crate_name(target: str) -> str:
    return f"fprime_rust_{target}"


def toml_path(path: Path) -> str:
    return path.resolve().as_posix()


def workspace_files(output: Path, target: str, runtime: Path, members: List[CrateMember]) -> Dict[Path, str]:
    """The workspace as {path: content}, deterministic in member order"""
    members = sorted(members, key=lambda member: member.name)
    root = root_crate_name(target)
    files: Dict[Path, str] = {}
    member_dirs = [member.name for member in members] + [root]
    workspace = ["# Generated by fprime-rust-ac crate; do not edit", "[workspace]", "resolver = \"2\"",
                 "members = [" + ", ".join(f'"{name}"' for name in member_dirs) + "]", "",
                 "[workspace.lints.rust]", "unsafe_op_in_unsafe_fn = \"deny\"", "unused_must_use = \"deny\"", "",
                 "[workspace.lints.clippy]"] + [f"{lint} = \"deny\"" for lint in CLIPPY_DENY] + [""]
    for profile in ("dev", "release"):
        workspace += [f"[profile.{profile}]"] + PROFILE_SETTINGS + [""]
    files[output / "Cargo.toml"] = "\n".join(workspace)
    for member in members:
        files[output / member.name / "Cargo.toml"] = "\n".join([
            "# Generated by fprime-rust-ac crate; do not edit", "[package]", f'name = "{member.name}"',
            'version = "0.1.0"', 'edition = "2021"', "", "[lib]", 'crate-type = ["rlib"]', "",
            "[dependencies]", f'fprime-rust = {{ path = "{toml_path(runtime)}" }}', "", "[lints]", "workspace = true", ""])
        files[output / member.name / "src" / "lib.rs"] = "\n".join([
            f"//! Generated by fprime-rust-ac crate; do not edit. Rust component `{member.qualified_name}`",
            "#![allow(non_snake_case, non_camel_case_types)]", "",
            f'#[path = "{toml_path(member.base_file)}"]', f"pub mod {member.base_module};",
            f'#[path = "{toml_path(member.user_file)}"]', f"pub mod {member.user_module};", "",
            f"pub use {member.base_module}::*;", ""])
    deps = [f'fprime-rust = {{ path = "{toml_path(runtime)}" }}'] + [
        f'{member.name} = {{ path = "../{member.name}" }}' for member in members]
    files[output / root / "Cargo.toml"] = "\n".join([
        "# Generated by fprime-rust-ac crate; do not edit", "[package]", f'name = "{root}"', 'version = "0.1.0"',
        'edition = "2021"', "", "[lib]", f'name = "{root}"', 'crate-type = ["staticlib"]', "", "[dependencies]"] + deps
        + ["", "[lints]", "workspace = true", ""])
    files[output / root / "src" / "lib.rs"] = "\n".join(
        [f"//! Generated by fprime-rust-ac crate; do not edit. Rust archive of executable `{target}`",
         "#![allow(non_snake_case)]", "", "pub use fprime_rust;"] + [f"pub use {member.name};" for member in members] + [""])
    return files


def write_if_changed(path: Path, content: str) -> bool:
    """Write ``content`` to ``path`` unless identical, keeping mtimes (and cargo's fingerprints) stable"""
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True
